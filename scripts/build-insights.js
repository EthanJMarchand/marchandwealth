// Pre-renders every /insights/<slug> article as a real static HTML file, and
// statically fills in the article grid + schema on insights.html.
//
// Why this exists: insight.html is a single shared template that used to get
// its title/canonical/meta/content filled in entirely by script.js at
// runtime. Googlebot's initial (non-JS) crawl only ever saw that template's
// generic defaults — every article's raw canonical tag pointed at
// insights.html — so Google indexed none of the articles under their own
// URLs ("Alternate page with proper canonical tag" in Search Console).
//
// This script bakes the real per-post values into the HTML at build time.
// script.js still runs client-side afterward and re-applies the exact same
// values (same slug-detection logic), so it's a no-op there — this only
// changes what's present before any JS executes.
//
// Run via `npm run build:insights` (wired into the Netlify build command in
// netlify.toml). Re-run whenever insights-data.js changes; the output in
// insights/ is generated and checked in, not hand-edited.
const fs = require('fs');
const path = require('path');
const INSIGHTS_POSTS = require('../insights-data.js');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'insights');
const SITE_URL = 'https://marchandwealth.ca';
const GENERATED_NOTICE = '<!-- AUTO-GENERATED by scripts/build-insights.js from insights-data.js — do not hand-edit. Run `npm run build:insights` after changing that file. -->';

const escapeHtml = (str) => String(str)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;');

const formatPostDate = (iso) => new Intl.DateTimeFormat('en-CA', { year: 'numeric', month: 'long', day: 'numeric' }).format(new Date(iso + 'T00:00:00'));

const sortedPosts = [...INSIGHTS_POSTS].sort((a, b) => new Date(b.datePublished) - new Date(a.datePublished));

// Same markup script.js builds client-side (postCardHtml) — kept in sync by hand.
const postCardHtml = (post) => `
      <a href="/insights/${post.slug}" class="block bg-white border border-line rounded-sm p-8 hover:-translate-y-1 hover:shadow-lg transition">
        <div class="text-[12px] font-semibold tracking-[0.14em] uppercase text-golddim mb-3">${escapeHtml(post.category)}</div>
        <h3 class="font-serif font-semibold text-xl text-navydeep mb-3 leading-snug">${escapeHtml(post.title)}</h3>
        <p class="text-[14.5px] text-inksoft leading-relaxed mb-5">${escapeHtml(post.excerpt)}</p>
        <div class="flex items-center justify-between text-[12.5px] text-inksoft">
          <span>${formatPostDate(post.datePublished)} &middot; ${escapeHtml(post.readTime)}</span>
          <span class="text-navydeep font-semibold">Read article &rarr;</span>
        </div>
      </a>`;

// Replaces the inner content of the first element with the given id.
// Walks nested same-tag pairs to find the true matching close tag, so this
// stays correct (and idempotent on re-runs) even when `content` itself
// contains further elements of the same tag name — e.g. injecting post
// cards, each with their own nested <div>s, into a <div id="insights-grid">.
// A naive non-greedy regex would stop at the first nested </div> instead.
function setText(html, id, content) {
  const openTagRe = new RegExp(`<([a-zA-Z0-9]+)([^>]*\\sid="${id}"[^>]*)>`);
  const openMatch = openTagRe.exec(html);
  if (!openMatch) throw new Error(`setText: no element with id="${id}" found`);
  const tag = openMatch[1];
  const openEnd = openMatch.index + openMatch[0].length;

  const openRe = new RegExp(`<${tag}\\b`, 'g');
  const closeRe = new RegExp(`</${tag}>`, 'g');
  let depth = 1;
  let pos = openEnd;
  while (depth > 0) {
    openRe.lastIndex = pos;
    closeRe.lastIndex = pos;
    const nextOpen = openRe.exec(html);
    const nextClose = closeRe.exec(html);
    if (!nextClose) throw new Error(`setText: no closing </${tag}> found for id="${id}"`);
    if (nextOpen && nextOpen.index < nextClose.index) {
      depth++;
      pos = nextOpen.index + nextOpen[0].length;
    } else {
      depth--;
      pos = nextClose.index + nextClose[0].length;
      if (depth === 0) {
        return html.slice(0, openEnd) + content + html.slice(nextClose.index);
      }
    }
  }
}

// Replaces one attribute's value on the first element with the given id.
function setAttr(html, id, attr, value) {
  const re = new RegExp(`(<[a-zA-Z0-9]+[^>]*\\sid="${id}"[^>]*\\s${attr}=")[^"]*(")`);
  if (!re.test(html)) throw new Error(`setAttr: no element with id="${id}" and attribute "${attr}" found`);
  return html.replace(re, (m, pre, post) => `${pre}${value}${post}`);
}

// JSON-LD embedded in a <script> tag — escape "<" so a literal "</script>"
// inside a string value can't prematurely close the tag.
const jsonScript = (obj) => JSON.stringify(obj).replace(/</g, '\\u003c');

function buildArticlePage(post) {
  const template = fs.readFileSync(path.join(ROOT, 'insight.html'), 'utf8');
  const postUrl = `${SITE_URL}/insights/${post.slug}`;
  const pageTitle = `${post.title} | Marchand Wealth`;
  const related = sortedPosts.filter(p => p.slug !== post.slug).slice(0, 2).map(postCardHtml).join('');
  const metaLine = `<span>${escapeHtml(post.author)}</span><span class="text-line">&middot;</span><span>${formatPostDate(post.datePublished)}</span><span class="text-line">&middot;</span><span>${escapeHtml(post.readTime)}</span>`;
  const categoryHtml = `<svg width="18" height="14" viewBox="0 0 20 16" fill="none"><path d="M1 2 L10 14 L19 2" stroke="currentColor" stroke-width="2.4"/></svg>${escapeHtml(post.category)}`;

  const postSchema = {
    '@context': 'https://schema.org',
    '@type': 'BlogPosting',
    headline: post.title,
    description: post.metaDescription,
    author: { '@type': 'Person', name: 'Ethan Marchand' },
    publisher: { '@type': 'Organization', name: 'Marchand Wealth', legalName: 'Marchand Financial Solutions Inc.', logo: { '@type': 'ImageObject', url: `${SITE_URL}/assets/logo.png` } },
    datePublished: post.datePublished,
    dateModified: post.dateModified,
    mainEntityOfPage: { '@type': 'WebPage', '@id': postUrl }
  };

  const breadcrumbSchema = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE_URL}/` },
      { '@type': 'ListItem', position: 2, name: 'Insights', item: `${SITE_URL}/insights.html` },
      { '@type': 'ListItem', position: 3, name: post.title, item: postUrl }
    ]
  };

  let html = template;

  html = setText(html, 'post-title-tag', escapeHtml(pageTitle));
  html = setAttr(html, 'post-meta-description', 'content', escapeHtml(post.metaDescription));
  html = setAttr(html, 'post-canonical', 'href', postUrl);
  html = setAttr(html, 'post-og-title', 'content', escapeHtml(post.title));
  html = setAttr(html, 'post-og-description', 'content', escapeHtml(post.metaDescription));
  html = setAttr(html, 'post-og-url', 'content', postUrl);

  html = html.replace(
    /(<script type="application\/ld\+json" id="post-breadcrumb-schema">)[\s\S]*?(<\/script>)/,
    (m, open, close) => `${open}\n${jsonScript(breadcrumbSchema)}\n${close}`
  );
  html = html.replace(
    /(<script type="application\/ld\+json" id="post-schema">)[\s\S]*?(<\/script>)/,
    (m, open, close) => `${open}\n${jsonScript(postSchema)}\n${close}`
  );

  html = setText(html, 'post-category', categoryHtml);
  html = setText(html, 'post-title', escapeHtml(post.title));
  html = setText(html, 'post-subtitle', escapeHtml(post.subtitle || ''));
  html = setText(html, 'post-meta', metaLine);
  html = setText(html, 'post-breadcrumb-current', escapeHtml(post.title));
  html = setText(html, 'post-content', post.content);
  html = setText(html, 'post-related', related);

  // Reveal the article by default so the raw HTML (pre-JS) already shows
  // real content, matching the state script.js settles into anyway.
  html = html.replace('<article id="post-article" class="hidden">', '<article id="post-article">');

  html = html.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n${GENERATED_NOTICE}`);

  return html;
}

function buildInsightsListing() {
  const filePath = path.join(ROOT, 'insights.html');
  let html = fs.readFileSync(filePath, 'utf8');

  const grid = sortedPosts.map(postCardHtml).join('');
  html = setText(html, 'insights-grid', grid);

  const blogSchema = {
    '@context': 'https://schema.org',
    '@type': 'Blog',
    name: 'Marchand Wealth Insights',
    url: `${SITE_URL}/insights.html`,
    publisher: { '@type': 'Organization', name: 'Marchand Wealth', legalName: 'Marchand Financial Solutions Inc.' },
    blogPost: sortedPosts.map(post => ({
      '@type': 'BlogPosting',
      headline: post.title,
      url: `${SITE_URL}/insights/${post.slug}`,
      datePublished: post.datePublished,
      dateModified: post.dateModified
    }))
  };
  html = html.replace(
    /(<script type="application\/ld\+json" id="blog-schema">)[\s\S]*?(<\/script>)/,
    (m, open, close) => `${open}\n${jsonScript(blogSchema)}\n${close}`
  );

  fs.writeFileSync(filePath, html);
}

if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR);

for (const post of sortedPosts) {
  const html = buildArticlePage(post);
  fs.writeFileSync(path.join(OUT_DIR, `${post.slug}.html`), html);
}

buildInsightsListing();

console.log(`Built ${sortedPosts.length} static article page(s) in insights/, and refreshed the insights.html grid.`);
